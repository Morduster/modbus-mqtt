# registers.py - карта регистров SW-2200A+ (инверторный контроллер насоса),
# протокол Modbus RTU: чтение 0x03, запись 0x06/0x10.
#
# Источник карты: документ «Инженерное меню SW-2200А.pdf» (инженерное меню
# SW-2200A). В документе параметры заданы кодами панели (группы F0..F4 и
# мониторинг d-00..d-28), а не адресами Modbus. Принято отображение —
# типовая для инверторов этого типа (MD/VFD) конвенция, требует проверки
# на живом устройстве:
#
#     код панели  ->  регистр Modbus
#     F0-nn       ->  nn           (0x0000 .. 0x001D)
#     F1-nn       ->  0x0100 + nn  (0x0100 .. 0x0109)
#     F2-nn       ->  0x0200 + nn  (0x0200 .. 0x0210)
#     F3-nn       ->  0x0300 + nn  (0x0300 .. 0x030C)
#     F4-nn       ->  0x0400 + nn  (0x0400 .. 0x0404)
#     d-nn        ->  0x0500 + nn  (0x0500 .. 0x051C)
#
# Как проверить: прочитайте 0x0307 (там должен быть адрес ведомого = 1) и
# 0x0308 (= 2 для стандартных 9600 бод). Если значения совпадают с тем, что
# показывает панель, базы верны; если нет — измените GROUP_BASE, вся карта
# пересчитается сама через _addr().
#
# ОГРАНИЧЕНИЕ ЖЕЛЕЗА: SW-2200A+ принимает максимум 8 регистров в одном
# запросе 0x03 (лимит контролируется в modbusrtu.MAX_REGS_PER_READ). Каждый
# блок ниже содержит <= 8 слов — за этим следит _validate() при импорте.
# Поля с разрывами в адресах (дыры, акционные позиции) пропускаются
# полем name=None.
#
# Все поля 16-битные: диапазоны из документа укладываются в u16/s16
# (только F0-17/F0-19 допускают отрицательные значения -> s16). 32-битных
# счётчиков в этой карте нет; тракт u32/s32 в декодере оставлен на случай
# расширения.
#
# Определение поля: (name, type, scale, unit, desc[, offset])
#
#   name   - имя, используемое в топике MQTT (<TOPIC_BASE>/<name>).
#            None = регистр пропускается: перепрыгивает адресную дыру либо
#            акционную позицию («Сохранить», сброс до заводских) или резерв.
#   type   - "u16" | "s16" | "u32" | "s32"
#   scale  - множитель сырого значения (колонка «единица измерения» документа).
#   unit   - единица измерения после масштабирования.
#   desc   - описание функции из документации; русские названия оставлены
#            намеренно — именно так подписаны позиции в PDF.
#   offset - необязательный, вычитается ДО масштабирования (здесь не используется).

# Сколько регистров занимает данный тип
REG_WIDTH = {"u16": 1, "s16": 1, "u32": 2, "s32": 2}

# Максимальное число регистров в одном запросе 0x03 (лимит SW-2200A+)
MAX_REGS_PER_READ = 8

# Базы групп параметров -> адреса Modbus (см. комментарий в начале файла)
GROUP_BASE = {
    "F0": 0x0000,
    "F1": 0x0100,
    "F2": 0x0200,
    "F3": 0x0300,
    "F4": 0x0400,
    "d":  0x0500,
}


def _addr(group, num):
    """Адрес Modbus для кода панели, напр. _addr("d", 12) -> 0x050C."""
    return GROUP_BASE[group] + num


