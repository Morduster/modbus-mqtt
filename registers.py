def block_size(block):
    """Сколько регистров нужно прочитать для всего блока."""
    return sum(REG_WIDTH[f[1]] for f in block["fields"])


def decode_block(block, words):
    """Преобразует список сырых регистров (u16) в список полей.

    Возвращает список кортежей (name, address, value, unit, desc) — поля
    с name=None пропускаются. Бросает ValueError, если слов меньше,
    чем требуется.
    """
    need = block_size(block)
    if len(words) < need:
        raise ValueError("блок 0x%04X: получено %d слов, ожидалось %d"
                         % (block["start"], len(words), need))

    out = []
    offset = 0
    for field in block["fields"]:
        name, typ, scale, unit, desc = field[:5]
        zero = field[5] if len(field) > 5 else 0
        width = REG_WIDTH[typ]

        if name is None:
            offset += width
            continue

        if width == 1:
            raw = words[offset]
            if typ == "s16" and raw & 0x8000:
                raw -= 0x10000
        else:
            # младшее слово первым — конвенция Deye/MD340; 32-битных полей
            # в этой карте нет, тракт оставлен на случай расширения
            raw = (words[offset + 1] << 16) | words[offset]
            if typ == "s32" and raw & 0x80000000:
                raw -= 0x100000000

        raw -= zero
        value = raw if scale == 1 else round(raw * scale, 3)
        out.append((name, block["start"] + offset, value, unit, desc))
        offset += width

    return out


def _validate():
    """Проверка целостности карты — вызывается при импорте, ловит опечатки."""
    names = set()
    for block in BLOCKS:
        size = block_size(block)
        if size > MAX_REGS_PER_READ:
            raise ValueError("registers.py: блок 0x%04X содержит %d регистров, лимит %d"
                             % (block["start"], size, MAX_REGS_PER_READ))
        for field in block["fields"]:
            if len(field) not in (5, 6):
                raise ValueError("registers.py: поле %r содержит %d элементов, ожидалось 5 или 6"
                                 % (field[0], len(field)))
            name, typ = field[0], field[1]
            if typ not in REG_WIDTH:
                raise ValueError("registers.py: неизвестный тип %r в блоке 0x%04X"
                                 % (typ, block["start"]))
            if name is None:
                continue
            if name in names:
                raise ValueError("registers.py: дубликат имени поля %r" % name)
            names.add(name)


_validate()

